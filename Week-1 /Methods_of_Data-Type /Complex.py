# 1. conjugate
# Q1: WAP to get the complex conjugate of a complex number
c = 3 + 4j
print("Conjugate:", c.conjugate())
# Q2: WAP to get the conjugate of a purely imaginary number
c = 5j
print("Conjugate:", c.conjugate())
# Q3: WAP to get the conjugate of a negative complex number
c = -2 - 3j
print("Conjugate:", c.conjugate())
# Q4: WAP to check the conjugate of a real-valued complex number
c = 7.0 + 0j
print("Conjugate:", c.conjugate())

# 2. imag

