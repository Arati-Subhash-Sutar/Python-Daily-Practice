# 1. bitwise and

# Q1: WAP to perform bitwise and on two integers
a = 5
b = 3
print("Bitwise AND:", a & b)
# Q2: WAP to perform bitwise and with zero
a = 12
b = 0
print("Bitwise AND:", a & b)
# Q3: WAP to perform bitwise and with identical numbers
a = 7
b = 7
print("Bitwise AND:", a & b)
# Q4: WAP to perform bitwise and on negative numbers
a = -5
b = 3
print("Bitwise AND:", a & b)


