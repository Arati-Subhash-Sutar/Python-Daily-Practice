# 1. in operator

# Q1: WAP to check if an element exists in a list using in
lst = [1, 2, 3, 4, 5]
print("Is element in list:", 3 in lst)
# Q2: WAP to check if a character exists in a string using in
s = "Python"
print("Is character in string:", "y" in s)
# Q3: WAP to check if a key exists in a dictionary using in
d = {"name": "Alice", "age": 25}
print("Is key in dictionary:", "name" in d)
# Q4: WAP to check if an element exists in a set using in
st = {10, 20, 30}
print("Is element in set:", 20 in st)


